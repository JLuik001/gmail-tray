"""Talking to fetchmail: rc rendering/import, running checks, parsing output.

fetchmail is always started with an argument list (never through a shell),
in the C locale so its output is parseable, with a private pid file so it
does not clash with a fetchmail daemon the user may run, and — in keyring
mode — with the run-control file piped through stdin, so passwords never
touch the disk.
"""

from __future__ import annotations

import logging
import os
import re
import shutil
import subprocess
import threading
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

from .config import Account, Config, ConfigError, managed_rc_path, runtime_dir

log = logging.getLogger(__name__)

GENERATED_HEADER = "# Generated by gmail-tray. Manage accounts with: gmail-tray --settings"
CHECK_TIMEOUT = 90  # seconds for a whole fetchmail run
POLL_TIMEOUT = 45   # per-server network timeout passed to fetchmail

EXIT_MESSAGES = {
    2: "Cannot connect to the server",
    3: "Authentication failed (for Gmail use an app password)",
    4: "Protocol error",
    5: "fetchmail rejected its configuration",
    6: "fetchmail run-control file must have 0600 permissions",
    7: "The server reported an error",
    8: "Another fetchmail instance is blocking the check",
    9: "Mailbox is locked on the server",
    11: "DNS lookup failed",
    14: "The server is busy, try again later",
    23: "fetchmail internal error",
}

# fetchmail >= 6.5 prefixes every report line with "Mon DD HH:MM:SS fetchmail: ";
# 6.4 only prefixes some lines with "fetchmail: ". Accept both.
_PREFIX = r"(?:[A-Z][a-z]{2} +\d{1,2} \d{2}:\d{2}:\d{2} )?(?:\S*fetchmail: )?"
_PREFIX_RE = re.compile("^" + _PREFIX)
_MAIL_RE = re.compile(
    "^" + _PREFIX + r"(\d+) messages? (?:\((\d+) seen\) )?for (.+?) at (\S+?)"
    r"(?: \(folder (.*?)\))?(?: \(\d+ octets\))?\.$"
)
_NOMAIL_RE = re.compile("^" + _PREFIX + r"No mail for (.+?) at (\S+?)(?: \(folder (.*?)\))?\.?$")


class FetchmailError(RuntimeError):
    pass


@dataclass
class AccountStatus:
    user: str
    server: str
    unread: int | None = None
    total: int | None = None
    error: str | None = None

    @property
    def ok(self) -> bool:
        return self.error is None and self.unread is not None

    @property
    def key(self) -> tuple[str, str]:
        return (self.user.lower(), self.server.lower())


# ---------------------------------------------------------------- rc files

def rc_quote(value: str) -> str:
    if re.search(r"[\x00-\x1f\x7f]", value):
        raise ConfigError("value contains control characters")
    # fetchmail's lexer mishandles \" inside double quotes, but understands
    # octal escapes; \042 is always exactly three digits, so it is unambiguous.
    return '"' + value.replace("\\", "\\\\").replace('"', "\\042") + '"'


_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f"}


def _unescape(s: str) -> str:
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c != "\\" or i + 1 >= len(s):
            out.append(c)
            i += 1
            continue
        n = s[i + 1]
        if n in "01234567":
            m = re.match(r"[0-7]{1,3}", s[i + 1:])
            out.append(chr(int(m.group(0), 8)))
            i += 1 + len(m.group(0))
        elif n == "x" and re.match(r"[0-9A-Fa-f]{1,2}", s[i + 2:]):
            m = re.match(r"[0-9A-Fa-f]{1,2}", s[i + 2:])
            out.append(chr(int(m.group(0), 16)))
            i += 2 + len(m.group(0))
        else:
            out.append(_ESCAPES.get(n, n))
            i += 2
    return "".join(out)


def tokenize_rc(text: str) -> list[str]:
    """Split a .fetchmailrc into tokens, decoding quoted strings like fetchmail."""
    tokens, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c.isspace() or c in ",:;":
            i += 1
        elif c == "#":
            while i < n and text[i] != "\n":
                i += 1
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            tokens.append(_unescape(text[i + 1:j]))
            i = j + 1
        else:
            j = i
            while j < n and not text[j].isspace() and text[j] not in "#,:;\"'":
                j += 1
            tokens.append(text[i:j])
            i = j
    return tokens


def render_rc(entries: list[tuple[Account, str]], header: bool = True) -> str:
    """Render a fetchmail run-control file for (account, password) pairs."""
    lines = []
    if header:
        lines.append(GENERATED_HEADER)
    lines.append("set no syslog")
    for acc, password in entries:
        acc.validate()
        if not password:
            raise ConfigError(f"no password for {acc.user}")
        poll = f"poll {rc_quote(acc.server)} with proto {acc.protocol}"
        if acc.port:
            poll += f" service {rc_quote(str(acc.port))}"
        poll += f" timeout {POLL_TIMEOUT}"
        lines.append(poll)
        user = f"    user {rc_quote(acc.user)} password {rc_quote(password)}"
        # ssl = implicit TLS (993/995). Without it fetchmail 6.4+ insists on
        # STARTTLS, so a connection is never left in plain text. Certificates
        # are always verified.
        user += " ssl sslcertck" if acc.ssl else " sslcertck"
        if acc.folder and acc.protocol == "IMAP":
            user += f" folder {rc_quote(acc.folder)}"
        lines.append(user)
    return "\n".join(lines) + "\n"


def is_generated(path: Path) -> bool:
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.readline().rstrip("\n") == GENERATED_HEADER
    except OSError:
        return False


_NOISE = {"with", "and", "has", "wants", "options", "here", "there", "is", "to", "via"}


def parse_rc(text: str) -> list[tuple[Account, str]]:
    """Best-effort import of a hand-written .fetchmailrc.

    Understands the common subset: poll/server/skip, proto, port/service,
    user, pass/password, ssl, folder. Anything else is ignored.
    """
    tokens = tokenize_rc(text)

    results: list[tuple[Account, str]] = []
    server = None
    server_opts: dict = {}
    current: dict | None = None

    def flush():
        nonlocal current
        if current and server and current.get("user"):
            try:
                acc = Account(
                    user=current["user"], server=server,
                    protocol=current.get("protocol", server_opts.get("protocol", "IMAP")),
                    port=current.get("port", server_opts.get("port", 0)),
                    ssl=current.get("ssl", server_opts.get("ssl", False)),
                    folder=current.get("folder", ""),
                ).validate()
                results.append((acc, current.get("password", "")))
            except ConfigError as e:
                log.warning("Skipping account %s: %s", current.get("user"), e)
        current = None

    i = 0
    while i < len(tokens):
        tok = tokens[i]
        low = tok.lower()
        nxt = tokens[i + 1] if i + 1 < len(tokens) else None
        if low in ("poll", "server", "skip"):
            flush()
            server, server_opts = nxt, {}
            i += 2
            continue
        if low in ("user", "username") and nxt is not None:
            flush()
            current = {"user": nxt}
            i += 2
            continue
        target = current if current is not None else server_opts
        if low in ("proto", "protocol") and nxt:
            proto = nxt.upper()
            target["protocol"] = "POP3" if proto.startswith("POP") else "IMAP"
            i += 2
        elif low in ("port", "service") and nxt and nxt.isdigit():
            target["port"] = int(nxt)
            i += 2
        elif low in ("pass", "password") and nxt is not None:
            target["password"] = nxt
            i += 2
        elif low in ("folder", "folders") and nxt:
            target["folder"] = nxt.split(",")[0]
            i += 2
        elif low == "ssl":
            target["ssl"] = True
            i += 1
        elif low in _NOISE:
            i += 1
        else:
            i += 1
    flush()
    # Merge 993/995 implicit-SSL ports: those mean ssl even if "ssl" was missing.
    for acc, _ in results:
        if acc.port in (993, 995):
            acc.ssl = True
    return results


# ---------------------------------------------------------------- running

def fetchmail_binary() -> str | None:
    return shutil.which("fetchmail")


def _run(rc_text: str | None = None, rc_path: Path | None = None) -> subprocess.CompletedProcess:
    exe = fetchmail_binary()
    if not exe:
        raise FetchmailError("fetchmail is not installed")
    pidfile = runtime_dir() / f"fetchmail-{os.getpid()}-{threading.get_ident()}.pid"
    cmd = [exe, "--check", "--nosyslog", "--pidfile", str(pidfile),
           "--fetchmailrc", "-" if rc_text is not None else str(rc_path)]
    env = dict(os.environ, LC_ALL="C", LANG="C")
    env.pop("LANGUAGE", None)
    try:
        # Empty stdin in file mode: fetchmail must never sit waiting for a password prompt.
        return subprocess.run(cmd, input=rc_text if rc_text is not None else "",
                              capture_output=True, text=True, timeout=CHECK_TIMEOUT, env=env)
    except subprocess.TimeoutExpired as e:
        raise FetchmailError("fetchmail timed out") from e
    except OSError as e:
        raise FetchmailError(f"cannot run fetchmail: {e}") from e


def parse_output(stdout: str) -> list[AccountStatus]:
    out = []
    for line in stdout.splitlines():
        line = line.strip()
        m = _MAIL_RE.match(line)
        if m:
            total = int(m.group(1))
            seen = int(m.group(2) or 0)
            out.append(AccountStatus(m.group(3), m.group(4), unread=max(total - seen, 0), total=total))
            continue
        m = _NOMAIL_RE.match(line)
        if m:
            out.append(AccountStatus(m.group(1), m.group(2), unread=0, total=0))
    return out


def _error_text(proc: subprocess.CompletedProcess) -> str:
    base = EXIT_MESSAGES.get(proc.returncode, f"fetchmail exited with code {proc.returncode}")
    detail = ""
    for line in reversed(proc.stderr.strip().splitlines()):
        line = _PREFIX_RE.sub("", line.strip())
        if line and "Running as root" not in line and not line.startswith("For help"):
            detail = line
            break
    if detail and detail.lower() not in base.lower():
        return f"{base}: {detail}"[:300]
    return base


def check_account(acc: Account, password: str) -> AccountStatus:
    """Check one managed account. Password goes to fetchmail via stdin only."""
    try:
        proc = _run(rc_text=render_rc([(acc, password)], header=False))
    except (FetchmailError, ConfigError) as e:
        return AccountStatus(acc.user, acc.server, error=str(e))
    parsed = parse_output(proc.stdout)
    if parsed and proc.returncode in (0, 1):
        st = parsed[0]
        return AccountStatus(acc.user, acc.server, st.unread, st.total)
    if proc.returncode == 1:
        return AccountStatus(acc.user, acc.server, 0, 0)
    log.debug("fetchmail stderr for %s: %s", acc.user, proc.stderr.strip())
    return AccountStatus(acc.user, acc.server, error=_error_text(proc))


def check_rcfile(path: Path, expected: list[Account] | None = None) -> list[AccountStatus]:
    """Check every account in an existing run-control file."""
    if not path.exists():
        return [AccountStatus("fetchmail", "", error=f"{path} does not exist — add an account in Settings")]
    try:
        mode = path.stat().st_mode
        if mode & 0o077:
            return [AccountStatus("fetchmail", "", error=f"{path} is readable by others — run: chmod 600 {path}")]
    except OSError as e:
        return [AccountStatus("fetchmail", "", error=str(e))]
    try:
        proc = _run(rc_path=path)
    except FetchmailError as e:
        return [AccountStatus("fetchmail", "", error=str(e))]
    parsed = parse_output(proc.stdout)
    failed = proc.returncode not in (0, 1)
    err = _error_text(proc) if failed else None
    if expected:
        by_key = {s.key: s for s in parsed}
        return [by_key.get(a.key) or AccountStatus(a.user, a.server, error=err or "No answer from fetchmail")
                for a in expected]
    if not parsed and failed:
        return [AccountStatus("fetchmail", "", error=err)]
    if failed:
        parsed.append(AccountStatus("fetchmail", "", error=err))
    return parsed


def check_all(cfg: Config, password_lookup=None) -> list[AccountStatus]:
    """Check every configured account; never raises."""
    try:
        if cfg.managed and cfg.password_store == "keyring":
            if password_lookup is None:
                from . import secret_store
                password_lookup = secret_store.lookup
            # Keyring lookups one at a time (may trigger an unlock prompt),
            # then the network checks in parallel.
            results: dict[int, AccountStatus] = {}
            todo = []
            for i, acc in enumerate(cfg.accounts):
                try:
                    pw = password_lookup(acc)
                except Exception as e:  # keyring locked/unavailable
                    results[i] = AccountStatus(acc.user, acc.server, error=f"Keyring: {e}")
                    continue
                if not pw:
                    results[i] = AccountStatus(acc.user, acc.server,
                                               error="No password stored — set it in Settings")
                    continue
                todo.append((i, acc, pw))
            if todo:
                with ThreadPoolExecutor(max_workers=min(4, len(todo))) as pool:
                    futures = {i: pool.submit(check_account, acc, pw) for i, acc, pw in todo}
                    for i, fut in futures.items():
                        results[i] = fut.result()
            return [results[i] for i in range(len(cfg.accounts))]
        if cfg.managed:
            return check_rcfile(managed_rc_path(), cfg.accounts)
        return check_rcfile(cfg.fetchmailrc_path)
    except Exception as e:  # last-resort guard: the tray must keep running
        log.exception("Mail check failed")
        return [AccountStatus("fetchmail", "", error=str(e))]
