"""Configuration: paths, validation and atomic, private saving."""

from __future__ import annotations

import json
import logging
import os
import re
import stat
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urlparse

from . import APP_ID

log = logging.getLogger(__name__)

CONFIG_NAME = "gmail-tray-configs.json"
SYSTEM_DEFAULT_CONFIG = Path("/usr/share/gmail-tray") / CONFIG_NAME

PASSWORD_STORES = ("keyring", "fetchmailrc")
PROTOCOLS = ("IMAP", "POP3")
MIN_INTERVAL = 30
MAX_INTERVAL = 86400

_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
_HOSTNAME = re.compile(
    r"^(?=.{1,253}$)[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?"
    r"(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$"
)


class ConfigError(ValueError):
    """Raised when a configuration value is invalid."""


def config_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return Path(base) / APP_ID


def config_path() -> Path:
    return config_dir() / CONFIG_NAME


def managed_rc_path() -> Path:
    """fetchmail rc generated by gmail-tray in file mode (never ~/.fetchmailrc,
    which may hold the user's own delivery setup)."""
    return config_dir() / "fetchmailrc"


def runtime_dir() -> Path:
    """Private per-user directory for lock and pid files (never /tmp)."""
    base = os.environ.get("XDG_RUNTIME_DIR")
    if base and os.path.isdir(base):
        path = Path(base) / APP_ID
    else:
        path = Path(os.path.expanduser("~/.cache")) / APP_ID
    ensure_private_dir(path)
    return path


def ensure_private_dir(path: Path) -> None:
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    st = os.lstat(path)
    if stat.S_ISLNK(st.st_mode) or not stat.S_ISDIR(st.st_mode):
        raise ConfigError(f"{path} is not a real directory")
    if st.st_uid != os.getuid():
        raise ConfigError(f"{path} is not owned by the current user")
    if st.st_mode & 0o077:
        os.chmod(path, 0o700)


def atomic_write_private(path: Path, data: str | bytes) -> None:
    """Write *data* to *path* atomically with mode 0600."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        data = data.encode("utf-8")
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        try:
            os.fchmod(fd, 0o600)  # mkstemp already uses 0600; FAT USB sticks refuse chmod
        except OSError:
            pass
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise


def _check_text(name: str, value, max_len: int = 256, allow_empty: bool = True) -> str:
    if not isinstance(value, str):
        raise ConfigError(f"{name} must be a string")
    if _CONTROL.search(value):
        raise ConfigError(f"{name} contains control characters")
    if len(value) > max_len:
        raise ConfigError(f"{name} is too long")
    if not allow_empty and not value.strip():
        raise ConfigError(f"{name} must not be empty")
    return value


def validate_url(url: str) -> str:
    _check_text("url", url, 2048, allow_empty=False)
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc or " " in url:
        raise ConfigError("url must be a valid https:// address")
    return url


def validate_hostname(host: str) -> str:
    if not isinstance(host, str) or not _HOSTNAME.match(host):
        raise ConfigError(f"invalid server name: {host!r}")
    return host


@dataclass
class Account:
    user: str
    server: str = "imap.gmail.com"
    protocol: str = "IMAP"
    port: int = 0          # 0 = protocol default
    ssl: bool = True
    folder: str = ""       # IMAP only, empty = INBOX

    @property
    def key(self) -> tuple[str, str]:
        return (self.user.lower(), self.server.lower())

    @property
    def is_gmail(self) -> bool:
        return self.server.lower() in ("imap.gmail.com", "pop.gmail.com")

    def validate(self) -> "Account":
        _check_text("user", self.user, 254, allow_empty=False)
        if any(c in self.user for c in ' "\\'):
            raise ConfigError("user must not contain spaces, quotes or backslashes")
        validate_hostname(self.server)
        if self.protocol not in PROTOCOLS:
            raise ConfigError(f"protocol must be one of {', '.join(PROTOCOLS)}")
        if not isinstance(self.port, int) or isinstance(self.port, bool) or not 0 <= self.port <= 65535:
            raise ConfigError("port must be between 0 and 65535")
        if not isinstance(self.ssl, bool):
            raise ConfigError("ssl must be true or false")
        _check_text("folder", self.folder, 255)
        return self

    def to_dict(self) -> dict:
        return {"user": self.user, "server": self.server, "protocol": self.protocol,
                "port": self.port, "ssl": self.ssl, "folder": self.folder}

    @classmethod
    def from_dict(cls, d: dict) -> "Account":
        if not isinstance(d, dict):
            raise ConfigError("account entries must be objects")
        acc = cls(
            user=d.get("user", ""),
            server=d.get("server", "imap.gmail.com"),
            protocol=str(d.get("protocol", "IMAP")).upper(),
            port=d.get("port", 0),
            ssl=d.get("ssl", True),
            folder=d.get("folder", ""),
        )
        return acc.validate()


@dataclass
class Config:
    url: str = "https://mail.google.com"
    icon: str = "gmail-tray"
    title: str = "Gmail-Tray"
    interval: int = 60
    browser: str = ""                      # empty = system default browser
    flags: list[str] = field(default_factory=list)
    notifications: bool = True
    notification_timeout: int = 5          # seconds, 0 = until dismissed
    password_store: str = "keyring"
    fetchmailrc: str = "~/.fetchmailrc"   # hand-written rc used when no accounts are managed
    accounts: list[Account] = field(default_factory=list)
    extra: dict = field(default_factory=dict)  # unknown keys, preserved on save

    KNOWN = ("url", "icon", "title", "interval", "browser", "flags", "notifications",
             "notification_timeout", "password_store", "fetchmailrc", "accounts", "version")

    @property
    def fetchmailrc_path(self) -> Path:
        return Path(os.path.expanduser(self.fetchmailrc))

    @property
    def managed(self) -> bool:
        """True when accounts are managed by gmail-tray (not a hand-written rc)."""
        return bool(self.accounts)

    def validate(self) -> "Config":
        validate_url(self.url)
        _check_text("icon", self.icon, 1024, allow_empty=False)
        _check_text("title", self.title, 64, allow_empty=False)
        if not isinstance(self.interval, int) or isinstance(self.interval, bool):
            raise ConfigError("interval must be a whole number of seconds")
        if not MIN_INTERVAL <= self.interval <= MAX_INTERVAL:
            raise ConfigError(f"interval must be between {MIN_INTERVAL} and {MAX_INTERVAL} seconds")
        _check_text("browser", self.browser, 1024)
        if not isinstance(self.flags, list):
            raise ConfigError("flags must be a list")
        for flag in self.flags:
            _check_text("flag", flag, 1024)
        if not isinstance(self.notifications, bool):
            raise ConfigError("notifications must be true or false")
        if (not isinstance(self.notification_timeout, int) or isinstance(self.notification_timeout, bool)
                or not 0 <= self.notification_timeout <= 600):
            raise ConfigError("notification_timeout must be 0–600 seconds")
        if self.password_store not in PASSWORD_STORES:
            raise ConfigError(f"password_store must be one of {', '.join(PASSWORD_STORES)}")
        _check_text("fetchmailrc", self.fetchmailrc, 4096, allow_empty=False)
        seen = set()
        for acc in self.accounts:
            acc.validate()
            if acc.key in seen:
                raise ConfigError(f"duplicate account {acc.user} on {acc.server}")
            seen.add(acc.key)
        return self

    @classmethod
    def from_dict(cls, d: dict) -> "Config":
        if not isinstance(d, dict):
            raise ConfigError("configuration must be a JSON object")
        base = cls()
        flags = d.get("flags", base.flags)
        if isinstance(flags, str):
            flags = flags.split()
        cfg = cls(
            url=d.get("url", base.url),
            icon=d.get("icon", base.icon),
            title=d.get("title", base.title),
            interval=d.get("interval", base.interval),
            browser=d.get("browser", base.browser),
            flags=list(flags) if isinstance(flags, list) else flags,
            notifications=d.get("notifications", base.notifications),
            notification_timeout=d.get("notification_timeout", base.notification_timeout),
            password_store=d.get("password_store", base.password_store),
            fetchmailrc=d.get("fetchmailrc", base.fetchmailrc),
            accounts=[Account.from_dict(a) for a in d.get("accounts", [])],
            extra={k: v for k, v in d.items() if k not in cls.KNOWN},
        )
        # Old configs may use a shorter interval than we now allow: clamp instead of failing.
        if isinstance(cfg.interval, int) and not isinstance(cfg.interval, bool):
            cfg.interval = max(MIN_INTERVAL, min(MAX_INTERVAL, cfg.interval))
        return cfg.validate()

    def to_dict(self) -> dict:
        d = dict(self.extra)
        d.update({
            "version": 2,
            "url": self.url,
            "icon": self.icon,
            "title": self.title,
            "interval": self.interval,
            "browser": self.browser,
            "flags": list(self.flags),
            "notifications": self.notifications,
            "notification_timeout": self.notification_timeout,
            "password_store": self.password_store,
            "fetchmailrc": self.fetchmailrc,
            "accounts": [a.to_dict() for a in self.accounts],
        })
        return d


def load(path: Path | None = None) -> Config:
    """Load the user config, creating it from defaults on first run."""
    path = Path(path) if path else config_path()
    if not path.exists():
        log.info("No configuration at %s, creating defaults", path)
        cfg = Config()
        if SYSTEM_DEFAULT_CONFIG.exists():
            try:
                cfg = Config.from_dict(json.loads(SYSTEM_DEFAULT_CONFIG.read_text(encoding="utf-8")))
            except (OSError, ValueError) as e:
                log.warning("Ignoring broken system default config: %s", e)
        save(cfg, path)
        return cfg
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise ConfigError(f"{path}: invalid JSON ({e})") from e
    cfg = Config.from_dict(data)
    # Tighten permissions of configs created by older versions.
    try:
        if path.stat().st_mode & 0o077:
            os.chmod(path, 0o600)
    except OSError:
        pass
    return cfg


def save(cfg: Config, path: Path | None = None) -> None:
    path = Path(path) if path else config_path()
    cfg.validate()
    if path.parent == config_dir():
        ensure_private_dir(path.parent)
    atomic_write_private(path, json.dumps(cfg.to_dict(), indent=4) + "\n")
